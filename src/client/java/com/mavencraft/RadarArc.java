package com.mavencraft;

public class RadarArc {

    public float angle;

    public float width;

    public float alpha;

    public float distance;

    public RadarArc(
            float angle,
            float width,
            float alpha,
            float distance) {

        this.angle = angle;
        this.width = width;
        this.alpha = alpha;
        this.distance = distance;
    }
}
